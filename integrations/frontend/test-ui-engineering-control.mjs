#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import {
  analyzeUiFacts,
  canonicalDigest,
  compileUiPolicy,
  deriveUiQualityGate,
  lintReactTailwindSource,
  resolveUiPlatformProfile
} from "./ui-engineering-control.mjs";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPT_DIR, "../..");
const CLI = path.join(SCRIPT_DIR, "ui-engineering-control.mjs");
let assertions = 0;

function equal(actual, expected, message) {
  assertions += 1;
  assert.deepEqual(actual, expected, message);
}

function ok(value, message) {
  assertions += 1;
  assert.ok(value, message);
}

function findingIds(value) {
  return [...new Set((value.findings ?? value).map((finding) => finding.id))].sort();
}

function validBundle() {
  return {
    subject: { project: "fixture", commit: "a".repeat(40) },
    tokens: {
      "space.related": { type: "length", value: "0.5rem" },
      "space.section": { type: "length", value: "1.5rem" },
      "text.label": { type: "typography", value: { fontSize: "0.75rem", fontWeight: 500 } },
      "text.metric": { type: "typography", value: { fontSize: "2rem", fontWeight: 700 } },
      "surface.canvas": { type: "color", value: "oklch(0.98 0 0)" },
      "surface.raised": { type: "color", value: "oklch(1 0 0)" },
      "status.success": { type: "color", value: "oklch(0.55 0.16 145)" },
      "status.warning": { type: "color", value: "oklch(0.68 0.14 75)" }
    },
    recipes: [{
      id: "dashboard",
      owner: "design-system",
      requiredPrimitives: ["PageHeader", "MetricGrid", "ActionRow", "StatusBadge"],
      tokenRefs: ["space.related", "space.section", "text.label", "text.metric", "surface.canvas", "surface.raised"],
      expected: [
        { id: "metric-grid", screenId: "dashboard", role: "metric-grid", cardinality: 5, columns: 4, lastRowPolicy: "span-full" },
        { id: "pending-row", screenId: "dashboard", role: "action-row", interactive: true },
        { id: "page-title", screenId: "dashboard", role: "page-title" }
      ]
    }],
    components: [
      { id: "PageHeader", owner: "design-system" },
      { id: "MetricGrid", owner: "design-system" },
      { id: "ActionRow", owner: "design-system" },
      { id: "StatusBadge", owner: "design-system" }
    ],
    statuses: {
      approved: { semanticRole: "success", variant: "success", tokenRef: "status.success" },
      pending: { semanticRole: "warning", variant: "warning", tokenRef: "status.warning" }
    },
    locale: { id: "pt-BR", catalog: ["Aprovações", "Movimentações", "Não", "análise"] }
  };
}

const supported = resolveUiPlatformProfile({
  subject: { project: "fixture", commit: "a".repeat(40) },
  uiSurfaces: [{ id: "web", framework: "react", styling: "tailwind-v4", runtime: "web-dom" }]
});
equal(supported.resolution.status, "resolved", "React/Tailwind v4 web DOM must resolve.");
equal(supported.resolution.adapterId, "react-tailwind-v4", "The initial source adapter must be explicit.");

const unsupported = resolveUiPlatformProfile({
  subject: { project: "fixture", commit: "a".repeat(40) },
  uiSurfaces: [{ id: "native", framework: "flutter", styling: "material", runtime: "native" }]
});
equal(findingIds(unsupported), ["UI-ADAPTER-UNSUPPORTED"], "Unsupported UI surfaces must fail closed.");

const compiled = compileUiPolicy(validBundle(), supported.profile, supported.resolution);
equal(compiled.findings, [], "A resolved design bundle must compile without findings.");
equal(compiled.expectedRenderModel.elements.length, 3, "Expected coverage must be generated by recipes.");
ok(compiled.tailwindCss.includes("@theme inline"), "Tailwind v4 semantic variables must be emitted through @theme inline.");
ok(compiled.policy.allowedUtilities.includes("text-metric"), "The compiler must emit complete statically detectable utility names.");
equal(
  canonicalDigest({ b: 2, a: 1, generatedAt: "today", absolutePath: "/tmp/a" }),
  canonicalDigest({ absolutePath: "/elsewhere", a: 1, generatedAt: "tomorrow", b: 2 }),
  "Volatile fields and key order must not change semantic digests."
);

const orphan = validBundle();
orphan.tokens["space.orphan"] = { type: "length", value: "3rem" };
equal(findingIds(compileUiPolicy(orphan, supported.profile, supported.resolution)), ["UI-TOKEN-ORPHAN"], "Orphan tokens must block compilation.");

const badSource = `
export function Dashboard({ tone, onOpen }) {
  return <>
    <fieldset><legend>Aprovacoes</legend></fieldset>
    <h2 className="font-serif">Movimentacoes</h2>
    <section data-metric-count="5" className="grid grid-cols-4"><Metric /><Metric /><Metric /><Metric /><Metric /></section>
    <span data-domain-status="approved pending" className="bg-amber-100 text-amber-800">Status</span>
    <div onClick={onOpen} className="flex items-center justify-between transition-all bg-slate-950 hover:bg-slate-900">Abrir</div>
    <div style={{ color: '#fff' }} className={\`bg-\${tone}-500\`}>Nao ha analise</div>
  </>;
}`;
equal(findingIds(lintReactTailwindSource(badSource, compiled.policy)), [
  "UI-01",
  "UI-02",
  "UI-04",
  "UI-05",
  "UI-06",
  "UI-08",
  "UI-09",
  "UI-10",
  "UI-SOURCE-DYNAMIC-UTILITY",
  "UI-SOURCE-INLINE-STYLE",
  "UI-SOURCE-TRANSITION-ALL"
].sort(), "Source prevention must emit stable causal and technical IDs.");
equal(findingIds(lintReactTailwindSource("export const Copy = () => <p>Texto não catalogado</p>;", compiled.policy)), ["UI-10"], "Visible JSX literals outside the compiled pt-BR catalog must fail.");
equal(findingIds(lintReactTailwindSource("export const Copy = () => <button aria-label=\"Aprovações\">Aprovações</button>;", compiled.policy)), [], "Cataloged visible and accessible copy must pass.");

const expected = {
  elements: Array.from({ length: 20 }, (_, index) => ({ id: `item-${index + 1}`, role: "item" })),
  relations: {
    grid: { id: "metrics", cardinality: 5, columns: 4, lastRowPolicy: null },
    proximity: { id: "pending", expectedGapPx: 8 },
    typeRoles: { label: { fontSizePx: 12, fontWeight: 500 }, metric: { fontSizePx: 32, fontWeight: 700 } },
    surfaces: { canvas: "rgb(250, 250, 250)", raised: "rgb(255, 255, 255)" }
  }
};
const rendered = {
  elements: [{ id: "item-1", role: "item" }],
  relations: {
    proximity: { id: "pending", actualGapPx: 96 },
    typeRoles: { label: { fontSizePx: 16, fontWeight: 400 }, metric: { fontSizePx: 18, fontWeight: 500 } },
    surfaces: { canvas: "rgb(255, 255, 255)", raised: "rgb(255, 255, 255)" }
  },
  accessibility: [{ id: "axe-name", severity: "P1", message: "Missing name" }]
};
const analyzed = analyzeUiFacts(expected, rendered);
equal(analyzed.coverage.missing.length, 19, "Coverage must compute expected minus observed.");
equal(findingIds(analyzed), ["UI-01", "UI-02", "UI-03", "UI-06", "UI-A11Y-AXE", "UI-COVERAGE-MISSING"].sort(), "Relational analyzers must derive objective findings.");

const cleanAnalysis = analyzeUiFacts(
  { elements: [{ id: "a", role: "item" }] },
  { elements: [{ id: "a", role: "item" }], accessibility: [] }
);
equal(cleanAnalysis.findings, [], "Equivalent facts from any adapter must yield a clean kernel result.");

const blockedGate = deriveUiQualityGate(analyzed.findings, {
  critique: { findings: [] },
  scorecard: { status: "approved", passed: true }
});
equal(blockedGate.eligible, false, "Perceptual inputs must not erase objective findings.");
ok(blockedGate.blockingFindingIds.includes("UI-A11Y-AXE"), "Accessibility must remain blocking.");
ok(blockedGate.blockingFindingIds.includes("UI-CAPABILITY-NOT-RUN"), "Programmatic callers cannot bypass missing capability receipts.");

const receiptSubject = { project: "fixture", commit: "a".repeat(40) };
const receipts = [
  ["profile", "frontend-ui-policy-control"],
  ["compile", "frontend-ui-policy-control"],
  ["lint", "frontend-ui-source-control"],
  ["collect", "frontend-ui-render-control"],
  ["analyze", "frontend-ui-render-control"]
].map(([command, capabilityId]) => ({ capabilityId, command: [command], subject: receiptSubject, exitCode: 0, semanticDigest: canonicalDigest({ command, capabilityId }) }));
const eligibleGate = deriveUiQualityGate({ ...cleanAnalysis, subject: receiptSubject }, {}, receipts);
equal(eligibleGate.eligible, false, "Hand-authored receipt-shaped objects cannot make a clean analysis eligible.");
ok(eligibleGate.blockingFindingIds.includes("UI-CAPABILITY-RECEIPT-INVALID"), "Programmatic gate calls must verify receipt digests and files.");
const failedReceiptGate = deriveUiQualityGate({ ...cleanAnalysis, subject: receiptSubject }, {}, receipts.map((receipt, index) => index === 3 ? { ...receipt, exitCode: 1 } : receipt));
ok(failedReceiptGate.blockingFindingIds.includes("UI-CAPABILITY-RECEIPT-FAILED"), "A non-zero capability execution must block eligibility.");
const staleReceiptGate = deriveUiQualityGate({ ...cleanAnalysis, subject: receiptSubject }, {}, receipts.map((receipt, index) => index === 0 ? { ...receipt, subject: { ...receiptSubject, commit: "b".repeat(40) } } : receipt));
ok(staleReceiptGate.blockingFindingIds.includes("UI-CAPABILITY-RECEIPT-STALE"), "A receipt from another commit must block eligibility.");

// RULE-FE-UI-RENDER-001 demands deterministic browser facts, but `collect`
// without --url accepts hand-written observations and emits
// provenance.browser = null. A render receipt with no browserDigest is exactly
// that path, so it must block instead of passing as real render evidence.
const fabricatedRenderGate = deriveUiQualityGate(
  { ...cleanAnalysis, subject: receiptSubject },
  {},
  receipts.map((receipt) => (
    receipt.capabilityId === "frontend-ui-render-control"
      ? { ...receipt, browserDigest: null }
      : receipt
  ))
);
ok(
  fabricatedRenderGate.blockingFindingIds.includes("UI-RENDER-PROVENANCE-MISSING"),
  "Render evidence with no browser provenance must block the gate."
);
equal(fabricatedRenderGate.eligible, false, "Fabricated render evidence cannot make the gate eligible.");
equal(fabricatedRenderGate.renderProvenance.browserBacked, 0, "The gate must report how much render evidence is browser-backed.");

// A browser-backed render receipt must not trigger the provenance finding.
const browserBackedGate = deriveUiQualityGate(
  { ...cleanAnalysis, subject: receiptSubject },
  {},
  receipts.map((receipt) => (
    receipt.capabilityId === "frontend-ui-render-control"
      ? { ...receipt, browserDigest: canonicalDigest({ name: "chromium" }) }
      : receipt
  ))
);
ok(
  !browserBackedGate.blockingFindingIds.includes("UI-RENDER-PROVENANCE-MISSING"),
  "Browser-backed render evidence must not be reported as fabricated."
);

const temp = fs.mkdtempSync(path.join(os.tmpdir(), "ui-control-cli-"));
try {
  const input = path.join(temp, "profile.input.json");
  const outputDir = path.join(temp, "out");
  fs.writeFileSync(input, `${JSON.stringify({
    subject: { project: "fixture", commit: "a".repeat(40) },
    uiSurfaces: [{ id: "web", framework: "react", styling: "tailwind-v4", runtime: "web-dom" }]
  }, null, 2)}\n`);
  const result = spawnSync(process.execPath, [CLI, "profile", "--input", input, "--output-dir", outputDir], {
    cwd: ROOT,
    encoding: "utf8"
  });
  equal(result.status, 0, `profile CLI failed:\n${result.stderr}`);
  ok(fs.existsSync(path.join(outputDir, "ui-platform-profile.json")), "Profile artifact must be emitted.");
  ok(fs.existsSync(path.join(outputDir, "ui-adapter-resolution.json")), "Adapter resolution must be emitted.");
  ok(fs.existsSync(path.join(outputDir, "capability-receipt.json")), "A real command must emit its receipt.");

  const collectionInput = path.join(temp, "collection.input.json");
  const collection = {
    subject: { project: "fixture", commit: "a".repeat(40) },
    adapterId: "normalized-html-css",
    browser: { name: "chromium", version: "fixture" },
    fixtureDigest: "f".repeat(64),
    observations: [{ id: "a", role: "item", box: { x: 0, y: 0, width: 100, height: 40 } }]
  };
  fs.writeFileSync(collectionInput, `${JSON.stringify(collection, null, 2)}\n`);
  const collect = (directory) => spawnSync(process.execPath, [CLI, "collect", "--input", collectionInput, "--output-dir", directory], { cwd: ROOT, encoding: "utf8" });
  equal(collect(path.join(temp, "collect-a")).status, 0, "First normalized collection must pass.");
  equal(collect(path.join(temp, "collect-b")).status, 0, "Second normalized collection must pass.");
  const firstEvidence = JSON.parse(fs.readFileSync(path.join(temp, "collect-a/rendered-ui-evidence.json"), "utf8"));
  const secondEvidence = JSON.parse(fs.readFileSync(path.join(temp, "collect-b/rendered-ui-evidence.json"), "utf8"));
  equal(firstEvidence.semanticDigest, secondEvidence.semanticDigest, "Identical collections in different paths must have the same digest.");

  collection.browser.version = "mutated";
  fs.writeFileSync(collectionInput, `${JSON.stringify(collection, null, 2)}\n`);
  equal(collect(path.join(temp, "collect-c")).status, 0, "Mutated-provenance collection must still execute.");
  const mutatedEvidence = JSON.parse(fs.readFileSync(path.join(temp, "collect-c/rendered-ui-evidence.json"), "utf8"));
  ok(mutatedEvidence.semanticDigest !== firstEvidence.semanticDigest, "Changing browser provenance must change the evidence digest.");
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}

console.log(`UI engineering control tests passed (${assertions} assertions).`);
