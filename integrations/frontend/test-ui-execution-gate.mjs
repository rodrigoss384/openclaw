import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import os from "node:os";
import { spawnSync } from "node:child_process";
import { createUiExecutionFixture } from "./fixtures/execution.mjs";
import { deriveUiQualityGate, canonicalDigest, createHumanDecisionDraft } from "./ui-engineering-control.mjs";
import { freezeExecutionContext } from "../governance/stage-control.mjs";
const controller = path.join(import.meta.dirname, "ui-engineering-control.mjs");
const fixture = await createUiExecutionFixture();
const authorityDir = fs.mkdtempSync(path.join(os.tmpdir(), "sde-test-authority-"));
try {
  fixture.write(".specs/features/browser-fixture/applicability.md", "frontend: substantial\n");
  freezeExecutionContext({ root: fixture.root, feature: "browser-fixture", baseRef: fixture.subject.commit, frontendPaths: ["src"] });
  const output = path.join(fixture.root, ".specs/gate");
  const execute = () => spawnSync(process.execPath, [controller, "gate", "--feature", "browser-fixture", "--execution", fixture.executionPath, "--output-dir", output], { cwd: fixture.root, encoding: "utf8", timeout: 120000 });
  const passed = execute();
  assert.equal(passed.status, 0, passed.stderr + passed.stdout);
  const gate = JSON.parse(fs.readFileSync(path.join(output, "ui-quality-gate.json")));
  assert.equal(gate.eligible, true);
  assert.equal(gate.renderProvenance.browserBacked, 1);
  assert.equal(execute().status, 0, "Unchanged snapshot must support repeat verification");
  assert.equal(JSON.parse(fs.readFileSync(path.join(output, "ui-quality-gate.json"))).semanticDigest, gate.semanticDigest, "Stable browser facts must preserve authorization digest");
  const key = path.join(authorityDir, "key");
  assert.equal(spawnSync("ssh-keygen", ["-q", "-t", "ed25519", "-N", "", "-f", key]).status, 0);
  const signers = path.join(authorityDir, "allowed-signers");
  fs.writeFileSync(signers, `reviewer ${fs.readFileSync(`${key}.pub`, "utf8").trim()}\n`);
  const authority = path.join(authorityDir, "authority.json");
  fs.writeFileSync(authority, JSON.stringify({ principal: "reviewer", allowedSignersPath: signers, project: fixture.subject.project }));
  const decisionPath = fixture.write(".specs/decision.json", createHumanDecisionDraft(gate, { principal: "reviewer", decision: "approved", authorityScope: { kind: "release-authorization", evidenceRefs: [".specs/gate/ui-quality-gate.json"] } }));
  assert.equal(spawnSync("ssh-keygen", ["-Y", "sign", "-f", key, "-n", "sde-human-decision-v1", decisionPath]).status, 0);
  const verify = (...extra) => spawnSync(process.execPath, [controller, "verify-authorization", "--decision", decisionPath, "--signature", `${decisionPath}.sig`, "--gate", path.join(output, "ui-quality-gate.json"), ...extra], { cwd: fixture.root, encoding: "utf8", env: { ...process.env, SDE_HUMAN_AUTHORITY: authority } });
  assert.equal(verify().status, 0, "Host-authorized signed approval of current gate must pass");
  assert.notEqual(verify("--principal", "untrusted").status, 0);
  assert.notEqual(verify("--receipt", "fabricated.json").status, 0);
  assert.notEqual(verify("--report-only").status, 0);
  const sourcePath = path.join(fixture.root, "src/App.tsx"); const originalSource = fs.readFileSync(sourcePath);
  fs.appendFileSync(sourcePath, "\n// altered after approval\n");
  assert.notEqual(verify().status, 0, "Signed approval must not authorize an altered snapshot");
  fs.writeFileSync(sourcePath, originalSource);
  const read = (command, file) => JSON.parse(fs.readFileSync(path.join(output, "execution", command, file)));
  const receipts = ["profile", "compile", "lint", "collect", "analyze"].map(command => read(command, "capability-receipt.json"));
  const findings = read("analyze", "ui-findings.json");
  assert.equal(deriveUiQualityGate({ ...findings, findings: [{ id: "fake", severity: "P2" }] }, {}, receipts).eligible, false);
  const renderedPath = path.join(output, "execution/collect/rendered-ui-evidence.json");
  const rendered = JSON.parse(fs.readFileSync(renderedPath)); rendered.elements = []; rendered.semanticDigest = canonicalDigest(rendered); fs.writeFileSync(renderedPath, JSON.stringify(rendered));
  assert.equal(deriveUiQualityGate(findings, {}, receipts).eligible, false);
  const collectReceipt = receipts.find(receipt => receipt.command[0] === "collect");
  const retainedOutput = collectReceipt.outputs.find(item => path.resolve(collectReceipt.evidenceRoot.absolutePath, item.ref) === renderedPath);
  retainedOutput.sha256 = crypto.createHash("sha256").update(fs.readFileSync(renderedPath)).digest("hex");
  collectReceipt.semanticDigest = canonicalDigest(collectReceipt);
  assert.equal(deriveUiQualityGate(findings, {}, receipts).eligible, false, "Recalculated receipt hashes cannot disconnect analysis from its producer");
  fixture.write("src/omitted.tsx", "export const Missing = () => <div />;");
  const omitted = execute(); assert.notEqual(omitted.status, 0); assert.match(omitted.stderr, /omits frozen frontend scope/);
  fs.unlinkSync(path.join(fixture.root, "src/omitted.tsx"));
  const collect = path.join(fixture.root, fixture.request.collectRequest);
  fs.writeFileSync(collect, JSON.stringify({ subject: fixture.subject, observations: [], browser: { name: "chromium" } }));
  const failed = execute(); assert.notEqual(failed.status, 0); assert.match(failed.stderr, /real browser URL/);
  console.log("Fresh browser gate passed (19 assertions; Chromium executed, no skips).");
} finally { await fixture.close(); fs.rmSync(authorityDir, { recursive: true, force: true }); }
